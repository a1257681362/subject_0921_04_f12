-- 车辆台账
CREATE TABLE IF NOT EXISTS t_vehicle (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_no     VARCHAR(32)  NOT NULL,
    model        VARCHAR(64),
    status       VARCHAR(16)  NOT NULL DEFAULT 'IDLE',  -- IDLE 在库 / RENTING 出租中 / DISABLED 停用
    operator     VARCHAR(32)  NOT NULL,
    biz_time     TIMESTAMP    NOT NULL,
    request_no   VARCHAR(64)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vehicle_plate UNIQUE (plate_no),
    CONSTRAINT ck_vehicle_status CHECK (status IN ('IDLE', 'RENTING', 'DISABLED'))
);

-- 租车单（全量记录，不做物理删除：已结算/已归档只许冲销）
CREATE TABLE IF NOT EXISTS t_rental_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       VARCHAR(40)    NOT NULL,
    vehicle_id     BIGINT         NOT NULL,
    customer_name  VARCHAR(64)    NOT NULL,
    branch_code    VARCHAR(32),                    -- 归属网点（recon-1 对账按网点抽取，可空=未分派）
    status         VARCHAR(32)    NOT NULL DEFAULT 'CREATED',
    settle_amount  DECIMAL(12,2),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rental_order_no UNIQUE (order_no)
);

CREATE INDEX IF NOT EXISTS idx_rental_order_biz_time ON t_rental_order (biz_time);

-- recon-1：既有文件库补列
ALTER TABLE t_rental_order ADD COLUMN IF NOT EXISTS branch_code VARCHAR(32);

-- 交接记录（交车 PICKUP / 还车 RETURN）
CREATE TABLE IF NOT EXISTS t_rental_handover (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    type           VARCHAR(8)     NOT NULL,
    fuel_reading   INT            NOT NULL,
    damage_photos  VARCHAR(1000)  NOT NULL,
    remark         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_handover_type CHECK (type IN ('PICKUP', 'RETURN')),
    CONSTRAINT ck_handover_fuel CHECK (fuel_reading BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_handover_order ON t_rental_handover (order_id);

-- 订单事件流水
CREATE TABLE IF NOT EXISTS t_rental_order_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    event_type     VARCHAR(32)    NOT NULL,
    detail         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_event_order ON t_rental_order_event (order_id);

-- rental-fsm-1：既有文件库平滑迁移
ALTER TABLE t_rental_order ALTER COLUMN status SET DATA TYPE VARCHAR(32);
ALTER TABLE t_rental_order_event ALTER COLUMN event_type SET DATA TYPE VARCHAR(32);
ALTER TABLE t_rental_order DROP CONSTRAINT IF EXISTS ck_rental_order_status;

-- 状态流转历史
CREATE TABLE IF NOT EXISTS t_rental_order_transition (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    action         VARCHAR(32)    NOT NULL,
    from_status    VARCHAR(32)    NOT NULL,
    to_status      VARCHAR(32)    NOT NULL,
    from_version   INT            NOT NULL,
    to_version     INT            NOT NULL,
    handover_id    BIGINT,
    remark         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_transition_order ON t_rental_order_transition (order_id, id);

-- 租车单客户姓名拼音索引（rental-name-search-1）
CREATE TABLE IF NOT EXISTS t_rental_order_name_index (
    order_id         BIGINT       NOT NULL,
    customer_name    VARCHAR(64)  NOT NULL,
    normalized_name  VARCHAR(64),
    full_pinyin      VARCHAR(512),
    initials         VARCHAR(64),
    create_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_rental_order_name_index PRIMARY KEY (order_id)
);

-- 入口幂等请求记录
CREATE TABLE IF NOT EXISTS t_idempotent_request (
    request_no     VARCHAR(64)    PRIMARY KEY,
    status         VARCHAR(16)    NOT NULL,
    operator       VARCHAR(32),
    response_body  CLOB,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_idempotent_status CHECK (status IN ('PROCESSING', 'DONE', 'FAILED'))
);

-- turnover-1：车辆归属网点补列
ALTER TABLE t_vehicle ADD COLUMN IF NOT EXISTS branch_code VARCHAR(32);
